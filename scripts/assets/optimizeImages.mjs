import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname } from 'node:path';

import sharp from 'sharp';

import { collectImageUsages } from './catalog.mjs';
import {
  configSignature,
  generatedReleasePath,
  imageReleaseVersion,
  manifestPath,
  selectProfile,
  toMasterPath,
  toWebpOutputPath,
  toWebpRuntimePath,
} from './config.mjs';

const dryRun = process.argv.includes('--dry-run');
const force = process.argv.includes('--force');
const lessonFilter = getArgValue('--lesson');
const previousManifest = readJson(manifestPath, { entries: [] });
const previousEntries = new Map(
  (previousManifest.entries ?? []).map(entry => [entry.output, entry]),
);
const allUsages = collectImageUsages();
const activeOutputs = new Set(
  allUsages.map(usage => toWebpRuntimePath(usage.source)),
);
const usages = allUsages.filter(
  usage => !lessonFilter || usage.lessonIds.includes(lessonFilter),
);
let converted = 0;
let skipped = 0;
let sourceBytes = 0;
let outputBytes = 0;

for (const usage of usages) {
  const sourcePath = toMasterPath(usage.source);
  const outputRuntime = toWebpRuntimePath(usage.source);
  const outputPath = toWebpOutputPath(usage.source);
  if (!existsSync(sourcePath)) {
    throw new Error(`Missing master image: ${sourcePath}`);
  }

  const sourceBuffer = readFileSync(sourcePath);
  const sourceSha256 = sha256(sourceBuffer);
  const profile = selectProfile(usage);
  const previous = previousEntries.get(outputRuntime);
  const canSkip =
    !force &&
    existsSync(outputPath) &&
    previous?.sourceSha256 === sourceSha256 &&
    previous?.configSignature === configSignature &&
    previous?.profile === profile.name;

  sourceBytes += sourceBuffer.length;
  if (canSkip) {
    outputBytes += statSync(outputPath).size;
    skipped += 1;
    continue;
  }

  console.log(
    `${dryRun ? 'WOULD BUILD' : 'BUILD'} ${outputRuntime} ` +
      `(${profile.name}, max ${profile.options.maxEdge}px)`,
  );
  if (dryRun) {
    converted += 1;
    continue;
  }

  mkdirSync(dirname(outputPath), { recursive: true });
  const sourceMetadata = await sharp(sourceBuffer).metadata();
  const info = await sharp(sourceBuffer)
    .rotate()
    .resize({
      fit: 'inside',
      height: profile.options.maxEdge,
      width: profile.options.maxEdge,
      withoutEnlargement: true,
    })
    .webp({
      alphaQuality: profile.options.alphaQuality,
      effort: profile.options.effort,
      preset: profile.options.preset,
      quality: profile.options.quality,
      smartSubsample: profile.options.smartSubsample,
    })
    .toFile(outputPath);
  const outputBuffer = readFileSync(outputPath);
  outputBytes += outputBuffer.length;
  previousEntries.set(outputRuntime, {
    configSignature,
    hasAlpha: sourceMetadata.hasAlpha ?? false,
    height: info.height,
    lessonIds: usage.lessonIds,
    maxPercent: usage.maxPercent,
    output: outputRuntime,
    outputBytes: outputBuffer.length,
    outputSha256: sha256(outputBuffer),
    profile: profile.name,
    roles: usage.roles,
    sceneIds: usage.sceneIds,
    source: usage.source.replace(/\.(?:jpe?g|webp)$/iu, '.png'),
    sourceBytes: sourceBuffer.length,
    sourceSha256,
    width: info.width,
  });
  converted += 1;
}

if (!dryRun) {
  const entries = [...previousEntries.values()]
    .filter(entry => activeOutputs.has(entry.output))
    .sort((a, b) => a.output.localeCompare(b.output));
  const revision = sha256(
    Buffer.from(entries.map(entry => `${entry.output}:${entry.outputSha256}`).join('\n')),
  ).slice(0, 16);
  const generatedAt =
    previousManifest.revision === revision && previousManifest.generatedAt
      ? previousManifest.generatedAt
      : new Date().toISOString();
  writeFileSync(
    manifestPath,
    `${JSON.stringify(
      {
        configSignature,
        entries,
        generatedAt,
        releaseVersion: imageReleaseVersion,
        revision,
      },
      null,
      2,
    )}\n`,
  );
  writeFileSync(
    generatedReleasePath,
    `// Generated by scripts/assets/optimizeImages.mjs.\n` +
      `export const remoteAssetRelease = '${imageReleaseVersion}';\n` +
      `export const remoteImageRevision = '${revision}';\n`,
  );
}

console.log(`\nConverted : ${converted}`);
console.log(`Skipped   : ${skipped}`);
console.log(`Input     : ${formatSize(sourceBytes)}`);
if (!dryRun) {
  console.log(`Output    : ${formatSize(outputBytes)}`);
  console.log(
    `Saved     : ${sourceBytes > 0 ? ((1 - outputBytes / sourceBytes) * 100).toFixed(1) : '0.0'}%`,
  );
}

function readJson(filePath, fallback) {
  return existsSync(filePath)
    ? JSON.parse(readFileSync(filePath, 'utf8'))
    : fallback;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function getArgValue(name) {
  const prefix = `${name}=`;
  return process.argv.slice(2).find(arg => arg.startsWith(prefix))?.slice(prefix.length);
}

function formatSize(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(1)} MiB`;
}
