type LearningObjectInput = {
  id: EntityId;
  sceneId: AfternoonHomeSceneId;
  assetName: string;
  defaultAnimation?: string;
  isInteractive?: boolean;
  learningScope?: LearningScope;
  position: PercentRect;
  touchArea?: PercentRect;
  vocab?: VocabularyItem;
};

function learningObject({
  id,
  sceneId,
  assetName,
  defaultAnimation,
  isInteractive = true,
  learningScope,
  position,
  touchArea,
  vocab,
}: LearningObjectInput): SceneObject {
  return {
    id,
    asset: sceneImage(sceneId, assetName),
    defaultAnimation,
    isInteractive,
    learningScope,
    position,
    role: 'learning',
    touchArea,
    vocabId: vocab?.id,
  };
}

type SceneStepInput = Omit<SceneStep, 'vocabId'> & {
  vocab?: VocabularyItem;
};

function sceneStep({ vocab, ...input }: SceneStepInput): SceneStep {
  return {
    ...input,
    ...(vocab ? { vocabId: vocab.id } : {}),
  };
}

function dropZone(
  id: EntityId,
  position: PercentRect,
  touchArea?: PercentRect,
  learningScope?: LearningScope,
): DropZone {
  return {
    id,
    learningScope,
    position,
    touchArea,
  };
}

function rect(
  x: number,
  y: number,
  width: number,
  height: number,
): PercentRect {
  return { height, width, x, y };
}

function sceneImage(sceneId: AfternoonHomeSceneId, assetName: string) {
  return imageAsset(assetName, sceneImageSource(sceneId, assetName));
}

function sceneImageSource(sceneId: AfternoonHomeSceneId, assetName: string) {
  return `lessons/afternoon-home/${sceneId}/images/${assetName}.png`;
}

function bounce(targetObjectId: EntityId): SceneEffect {
  return {
    animation: 'bounce',
    targetObjectId,
    type: 'animation',
  };
}

function sparkle(targetObjectId: EntityId): SceneEffect {
  return {
    animation: 'sparkle',
    targetObjectId,
    type: 'animation',
  };
}

function sound(soundName: 'complete'): SceneEffect {
  return {
    sound: soundName,
    type: 'sound',
  };
}
