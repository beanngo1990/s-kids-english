type LearningObjectInput = {
  id: EntityId;
  sceneId: SnackSceneId;
  assetName: string;
  defaultAnimation?: string;
  isInteractive?: boolean;
  learningScope?: LearningScope;
  position: PercentRect;
  touchArea?: PercentRect;
  vocab?: VocabularyItem;
};

function learningObject({
  id,
  sceneId,
  assetName,
  defaultAnimation,
  isInteractive = true,
  learningScope,
  position,
  touchArea,
  vocab,
}: LearningObjectInput): SceneObject {
  return {
    id,
    asset: sceneImage(sceneId, assetName),
    defaultAnimation,
    isInteractive,
    learningScope,
    position,
    role: 'learning',
    touchArea,
    vocabId: vocab?.id,
  };
}

type BaseStepInput = Omit<SceneStep, 'interaction' | 'vocabId'> & {
  vocab?: VocabularyItem;
};

type TapStepInput = BaseStepInput & {
  correctObjectIds?: EntityId[];
  targetObjectId: EntityId;
};

type DragStepInput = TapStepInput & {
  dropZoneId: EntityId;
};

function listenStep({ vocab, ...input }: BaseStepInput): SceneStep {
  return sceneStep({
    ...input,
    interaction: {
      targetObjectId: input.targetObjectIds[0],
      type: 'listen',
    },
    vocab,
  });
}

function tapStep({
  correctObjectIds,
  targetObjectId,
  vocab,
  ...input
}: TapStepInput): SceneStep {
  return sceneStep({
    ...input,
    interaction: {
      correctObjectIds: correctObjectIds ?? [targetObjectId],
      targetObjectId,
      type: 'tap',
    },
    vocab,
  });
}

function dragStep({
  correctObjectIds,
  dropZoneId,
  targetObjectId,
  vocab,
  ...input
}: DragStepInput): SceneStep {
  return sceneStep({
    ...input,
    interaction: {
      correctObjectIds: correctObjectIds ?? [targetObjectId],
      dropZoneId,
      targetObjectId,
      type: 'drag',
    },
    vocab,
  });
}

type SceneStepInput = Omit<SceneStep, 'vocabId'> & {
  vocab?: VocabularyItem;
};

function sceneStep({ vocab, ...input }: SceneStepInput): SceneStep {
  return {
    ...input,
    ...(vocab ? { vocabId: vocab.id } : {}),
  };
}

function dropZone(
  id: EntityId,
  position: PercentRect,
  touchArea?: PercentRect,
  learningScope?: LearningScope,
): DropZone {
  return {
    id,
    learningScope,
    position,
    touchArea,
  };
}

function rect(
  x: number,
  y: number,
  width: number,
  height: number,
): PercentRect {
  return { height, width, x, y };
}

function sceneImage(sceneId: SnackSceneId, assetName: string) {
  return imageAsset(assetName, sceneImageSource(sceneId, assetName));
}

function sceneImageSource(sceneId: SnackSceneId, assetName: string) {
  return `lessons/snack-time/${sceneId}/images/${assetName}.png`;
}

function bounce(targetObjectId: EntityId): SceneEffect {
  return {
    animation: 'bounce',
    targetObjectId,
    type: 'animation',
  };
}

function sparkle(targetObjectId: EntityId): SceneEffect {
  return {
    animation: 'sparkle',
    targetObjectId,
    type: 'animation',
  };
}

function sound(soundName: 'complete'): SceneEffect {
  return {
    sound: soundName,
    type: 'sound',
  };
}
