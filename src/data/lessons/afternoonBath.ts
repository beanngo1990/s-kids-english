type LearningObjectInput = {
  id: EntityId;
  sceneId: AfternoonBathSceneId;
  assetName: string;
  defaultAnimation?: string;
  isInteractive?: boolean;
  learningScope?: LearningScope;
  position: PercentRect;
  touchArea?: PercentRect;
  vocab?: VocabularyItem;
};

function learningObject({
  id,
  sceneId,
  assetName,
  defaultAnimation,
  isInteractive = true,
  learningScope,
  position,
  touchArea,
  vocab,
}: LearningObjectInput): SceneObject {
  return {
    id,
    asset: sceneImage(sceneId, assetName),
    defaultAnimation,
    isInteractive,
    learningScope,
    position,
    role: 'learning',
    touchArea,
    vocabId: vocab?.id,
  };
}

